#!/usr/bin/env python3
"""Generate synthetic audio clips and reference MFCC features in vectors.h.

Requires torch==2.8.0 and torchaudio==2.8.0. Run from the SDK checkout:
    python tests/gen_reference.py
"""
import math
import pathlib

import torch
import torchaudio

SR, CLIP = 16000, 16000


def mfcc(pcm_int16: torch.Tensor) -> torch.Tensor:
    """MFCC settings for the kws-dscnn audio contract."""
    waveform = pcm_int16.to(torch.float32) / 32768.0
    transform = torchaudio.transforms.MFCC(
        sample_rate=SR, n_mfcc=10,
        melkwargs={"n_fft": 1024, "win_length": 640, "hop_length": 320, "n_mels": 40, "center": True},
    )
    feats = transform(waveform.unsqueeze(0)).permute(0, 2, 1)  # (1, T, 10)
    start = (feats.shape[1] - 49) // 2
    return feats[0, start:start + 49, :]


def clips() -> dict[str, torch.Tensor]:
    t = torch.arange(CLIP, dtype=torch.float64) / SR
    g = torch.Generator().manual_seed(1234)
    out = {}
    # tone burst with silence around it: exercises the clip-relative floor
    burst = torch.zeros(CLIP, dtype=torch.float64)
    burst[4000:9000] = 0.4 * torch.sin(2 * math.pi * 440 * t[4000:9000]) * torch.hann_window(5000, dtype=torch.float64)
    out["tone_burst"] = burst
    # chirp 100 Hz -> 6 kHz
    out["chirp"] = 0.3 * torch.sin(2 * math.pi * (100 * t + (6000 - 100) / 2 * t * t))
    # white noise, moderate level
    out["noise"] = 0.05 * torch.randn(CLIP, generator=g, dtype=torch.float64)
    # amplitude-modulated harmonics with a quiet tail, speech-like envelope
    env = torch.exp(-((t - 0.45) ** 2) / (2 * 0.12 ** 2))
    voiced = sum(torch.sin(2 * math.pi * 140 * k * t) / k for k in range(1, 8))
    out["am_harmonics"] = 0.25 * env * voiced
    out["zeros"] = torch.zeros(CLIP, dtype=torch.float64)
    return {k: (v.clamp(-1, 1) * 32767).round().to(torch.int16) for k, v in out.items()}


def c_array(name: str, values, ctype: str, per_line: int) -> str:
    body = []
    vals = list(values)
    for i in range(0, len(vals), per_line):
        body.append("    " + ", ".join(vals[i:i + per_line]) + ",")
    return f"static const {ctype} {name}[{len(vals)}] = {{\n" + "\n".join(body) + "\n};\n"


def main() -> None:
    parts = ["/* Generated by tests/gen_reference.py with torchaudio %s. Do not edit. */\n" % torchaudio.__version__,
             "#include <stdint.h>\n"]
    names = []
    for name, pcm in clips().items():
        feats = mfcc(pcm)
        parts.append(c_array(f"pcm_{name}", (str(int(v)) for v in pcm), "int16_t", 20))
        parts.append(c_array(f"mfcc_{name}", (f"{float(v):.6f}f" for v in feats.flatten()), "float", 10))
        names.append(name)
    parts.append("typedef struct { const char *name; const int16_t *pcm; const float *mfcc; } vector_t;\n")
    parts.append("static const vector_t VECTORS[] = {\n" +
                 "".join(f'    {{"{n}", pcm_{n}, mfcc_{n}}},\n' for n in names) + "};\n")
    parts.append(f"#define N_VECTORS {len(names)}\n")
    pathlib.Path(__file__).resolve().with_name("vectors.h").write_text("".join(parts))
    print(f"wrote tests/vectors.h with {len(names)} clips")


if __name__ == "__main__":
    main()
